import assert from 'node:assert/strict';
import { launch, evidence, screenshot } from './common.mjs';

const browser = await launch();
const results = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8082');
  const test = id => page.getByTestId(id);
  await test('prototype-toolbar').waitFor();
  await test('customer-a').click();
  await test('subjects-table').waitFor();
  assert.equal(await test('subject-row').count(), 2);
  assert.equal(await test('unknown-type').textContent(), '未知');
  assert.equal(await test('data-as-of').textContent(), '2026-11-02');
  await screenshot(page, 'prototype-normal.png');
  results.push('正常选择、身份、日期、缺失分类');
  await test('subject-search').fill('does-not-exist');
  await test('no-matching-subjects').waitFor();
  await test('clear-subject-search').click();
  await test('subjects-table').waitFor();
  await test('customer-search').fill('no-customer');
  assert.equal(await test('customer-a').count(), 0);
  await test('clear-customer-search').click();
  await test('customer-a').waitFor();
  results.push('客户及对象查询无结果、清除恢复');
  await test('scenario-select').selectOption('zero-subjects');
  await test('zero-subjects').waitFor();
  results.push('独立合成零对象');
  await test('scenario-select').selectOption('loading');
  await test('loading-state').waitFor();
  await test('customer-b').click();
  await test('zero-subjects').waitFor();
  await page.waitForTimeout(2200);
  assert.equal(await test('selected-customer-id').textContent(), 'synthetic-customer-b');
  assert.equal(await test('subjects-table').count(), 0);
  results.push('加载与快速切换不被旧响应覆盖');
  await test('scenario-select').selectOption('source-error');
  await test('source-error').waitFor();
  assert.equal(await test('snapshot-meta').isVisible(), false);
  await test('retry-source').click();
  await test('loading-directory').waitFor();
  await test('customer-a').waitFor();
  results.push('来源故障、隐藏旧数据、重试');
  await test('scenario-select').selectOption('forbidden');
  await test('forbidden').waitFor();
  await test('check-permission').click();
  await test('forbidden').waitFor();
  assert.equal(await test('customer-list').count(), 0);
  results.push('无权限保持拒绝');
  await test('scenario-select').selectOption('normal');
  await test('directory-toggle').click();
  await test('disabled').waitFor();
  await test('directory-toggle').click();
  await test('customer-a').waitFor();
  results.push('原型停用与启用反馈');
  await page.setViewportSize({ width: 390, height: 844 });
  await test('customer-a').click();
  await test('subjects-table').waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await screenshot(page, 'prototype-mobile.png');
  assert.deepEqual(errors, []);
  results.push('窄屏无页面横向溢出、无浏览器异常');
  await evidence('prototype.json', { passed: true, by: 'delegated-agent', tested_at: new Date().toISOString(), results });
  console.log(`Prototype: ${results.length} scenario groups passed`);
} finally {
  await browser.close();
}
