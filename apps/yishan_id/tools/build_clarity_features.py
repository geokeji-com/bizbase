"""Generate the static feature vocabulary using only versioned app schema JSON.

Run against source trees containing the standard Frappe apps plus this repo's apps.
Never point this at a site's exported records, fixtures, backups, or runtime database.
"""

import argparse
import json
import re
from pathlib import Path
from textwrap import wrap

KINDS = {"doctype": "DocType", "workspace": "Workspace", "page": "Page", "report": "Report", "dashboard": "Dashboard"}
APPS = ("frappe", "erpnext", "crm", "insights", "file_share", "yishan_id", "management_board", "sales_board", "ops_board", "customer_board")
TEMPLATE = """// Generated by tools/build_clarity_features.py from standard app schema. Never add record identifiers.
(() => {
  'use strict';
  const words = value => new Set(value.trim().split(/\\s+/));
  const schema = {
SCHEMA
  };
  const fixed = new Set(['/_usage/desk/home', '/_usage/web/print', '/_usage/web/banking']);
  function add(group, values) {
    for (const value of words(values)) fixed.add('/_usage/' + group + '/' + value);
  }
  add('file-share', 'list form view password unavailable');
  add('yishan-id', 'list form login');
  add('auth', 'login forgot-password reset-password signup email-link logout');
  add('website', `home other 404 error about attribution contact me message portal printview printpreview qrcode
    third-party-apps confirm-workflow-action modified-doc-alert banking support book-appointment book-appointment-verify
    jobs roster crm insights payment-setup-certification boms timesheets project tasks issues newsletters`);
  for (const feature of words('orders invoices supplier-quotations purchase-orders purchase-invoices quotations shipments rfq addresses material-requests')) {
    add('website', feature + ' ' + feature + '-detail');
  }
  const doctypeViews = words('list form tree print calendar kanban gantt image inbox map');
  function has(path) {
    if (fixed.has(path)) return true;
    if (typeof path !== 'string') return false;
    const parts = path.split('/');
    if (parts.length !== 5 || parts[0] !== '' || parts[1] !== '_usage' || parts[2] !== 'desk') return false;
    const [, , , view, slug] = parts;
    if (doctypeViews.has(view)) return slug === 'other' || slug === 'private' || schema.doctype.has(slug);
    if (!['report', 'dashboard', 'page', 'workspace'].includes(view)) return false;
    if (slug === 'other' || slug === 'private' || schema[view].has(slug)) return true;
    return (view === 'report' || view === 'dashboard') && schema.doctype.has(slug);
  }
  window.bizbaseUsageFeatures = Object.freeze({has});
})();
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('roots', type=Path, nargs='+', help='parent directories of app packages')
    args = parser.parse_args()
    names = {kind: set() for kind in KINDS}
    found = set()
    for root in args.roots:
        for app in APPS:
            pkg = root / app / app
            if not pkg.is_dir():
                continue
            found.add(app)
            # Standard module layout only, with matching module and file names.
            for kind, type_name in KINDS.items():
                for source in pkg.glob(f'*/{kind}/*/*.json'):
                    if source.stem != source.parent.name:
                        continue
                    data = json.loads(source.read_bytes())
                    if not isinstance(data, dict) or data.get('doctype') != type_name:
                        continue
                    if kind == 'workspace' and (not data.get('public') or data.get('for_user')):
                        continue
                    if data.get('custom') or (kind == 'report' and data.get('is_standard') != 'Yes'):
                        continue
                    raw = data.get('name', '')
                    if re.fullmatch(r'[a-zA-Z0-9 _-]+', raw):
                        slug = re.sub(r'[ _-]+', '-', raw.lower()).strip('-')
                        if slug and len(slug) <= 80:
                            names[kind].add(slug)
    if not set(APPS) <= found:
        parser.error('supply both the standard app source trees and the repository apps')
    rows = []
    for kind, slugs in names.items():
        text = '\n      '.join(wrap(' '.join(sorted(slugs)), width=110, break_on_hyphens=False, break_long_words=False))
        rows.append(f'    {kind}: words(`{text}`),')
    print(TEMPLATE.replace('SCHEMA', '\n'.join(rows)), end='')


if __name__ == '__main__':
    main()
